import { z } from 'zod';
import type { OpenDotsToolDefinition } from '../types.js';
import { globalFileWorkspace } from '../../files/file-workspace.js';

export const executionReportTool: OpenDotsToolDefinition<
  {
    title: string;
    objective: string;
    completedSteps: string[];
    filesCreated?: string[];
    keyFindings?: string[];
    unresolvedBlockers?: string[];
  },
  {
    reportFileName: string;
    relativePath: string;
    markdown: string;
    summary: string;
  }
> = {
  name: 'generate_execution_report',
  description:
    'Generate a formal, publication-ready execution report documenting completed work, files produced, and remaining blockers. Exports directly to the project workspace.',
  parameters: z.object({
    title: z.string().describe('Title of the task or milestone completed'),
    objective: z.string().describe('The primary objective or prompt fulfilled'),
    completedSteps: z.array(z.string()).describe('List of verified steps executed successfully'),
    filesCreated: z.array(z.string()).optional().describe('List of artifacts or files generated'),
    keyFindings: z.array(z.string()).optional().describe('Key discoveries, metrics, or insights gained'),
    unresolvedBlockers: z.array(z.string()).optional().describe('Any pending issues or recommended next actions'),
  }),
  requiredPermission: 'files',
  timeoutMs: 15_000,
  maxOutputChars: 25_000,
  execute: async (
    { title, objective, completedSteps, filesCreated = [], keyFindings = [], unresolvedBlockers = [] },
    _ctx,
  ) => {
    let md = `# Execution Deliverable: ${title}\n\n`;
    md += `*Generated by OpenDots Autonomous Agent on ${new Date().toISOString()}*\n\n`;
    md += `## Objective\n${objective}\n\n`;

    md += `## Completed Steps\n`;
    for (let i = 0; i < completedSteps.length; i++) {
      md += `${i + 1}. ${completedSteps[i]}\n`;
    }
    md += '\n';

    if (filesCreated.length > 0) {
      md += `## Artifacts & Workspace Files\n`;
      for (const file of filesCreated) {
        md += `- \`${file}\`\n`;
      }
      md += '\n';
    }

    if (keyFindings.length > 0) {
      md += `## Key Findings & Verification\n`;
      for (const finding of keyFindings) {
        md += `- ${finding}\n`;
      }
      md += '\n';
    }

    if (unresolvedBlockers.length > 0) {
      md += `## Pending Items & Blockers\n`;
      for (const item of unresolvedBlockers) {
        md += `- [ ] ${item}\n`;
      }
      md += '\n';
    } else {
      md += `## Status\nAll planned steps completed with zero outstanding blockers.\n\n`;
    }

    const exported = globalFileWorkspace.exportDocument(`Report_${title.slice(0, 30)}`, md, 'markdown');

    return {
      reportFileName: exported.name,
      relativePath: exported.relativePath,
      markdown: md,
      summary: `Execution report successfully generated and saved to "${exported.relativePath}".`,
    };
  },
};
